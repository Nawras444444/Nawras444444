// Slices each 4-panel storyboard sheet (public/sheets/sheet_0N.png) into
// 4 clean panels (public/panels/0N_1.png .. 0N_4.png), trimming the white
// gutters and the dark outer panel borders.
// Usage: node scripts/sliceSheets.js
const sharp = require("sharp");
const path = require("path");
const fs = require("fs");

const root = path.join(__dirname, "..");
const sheetsDir = path.join(root, "public", "sheets");
const outDir = path.join(root, "public", "panels");
const bgDir = path.join(outDir, "bg");
fs.mkdirSync(bgDir, { recursive: true });

const INSET = 6; // fixed inset that removes the thin dark panel outline

const rowMeans = (data, w, h) => {
  const out = new Float64Array(h);
  for (let y = 0; y < h; y++) {
    let s = 0;
    for (let x = 0; x < w; x++) s += data[y * w + x];
    out[y] = s / w;
  }
  return out;
};

const colMeans = (data, w, y0, y1) => {
  const out = new Float64Array(w);
  for (let x = 0; x < w; x++) {
    let s = 0;
    for (let y = y0; y < y1; y++) s += data[y * w + x];
    out[x] = s / (y1 - y0);
  }
  return out;
};

// Trim bright gutter lines, then a fixed inset for the dark outline.
// (Dark pixels are NOT trimmed adaptively: dark art like sleeves or storm
// clouds would be cut off.)
const trimEdges = (means, a, b) => {
  while (a < b && means[a] > 200) a++;
  while (b > a && means[b - 1] > 200) b--;
  return [a + INSET, b - INSET];
};

const sliceSheet = async (sheetIdx) => {
  const file = path.join(sheetsDir, `sheet_0${sheetIdx}.png`);
  const { data, info } = await sharp(file)
    .greyscale()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const rm = rowMeans(data, w, h);

  // Find white gutter bands (rows mean > 200)
  const gutters = [];
  let y = 0;
  while (y < h) {
    if (rm[y] > 200) {
      const s = y;
      while (y < h && rm[y] > 200) y++;
      gutters.push([s, y]);
    } else y++;
  }
  const bounds = [0, ...gutters.flat(), h];
  const bands = [];
  for (let i = 0; i < bounds.length; i += 2) {
    if (bounds[i + 1] - bounds[i] > 100) bands.push([bounds[i], bounds[i + 1]]);
  }
  if (bands.length !== 4) {
    throw new Error(`sheet_0${sheetIdx}: expected 4 panels, got ${bands.length}`);
  }

  for (let p = 0; p < 4; p++) {
    const [ry0, ry1] = trimEdges(rm, bands[p][0], bands[p][1]);
    const cm = colMeans(data, w, ry0, ry1);
    const [cx0, cx1] = trimEdges(cm, 0, w);
    const out = path.join(outDir, `0${sheetIdx}_${p + 1}.png`);
    await sharp(file)
      .extract({ left: cx0, top: ry0, width: cx1 - cx0, height: ry1 - ry0 })
      .png()
      .toFile(out);
    // Pre-blurred, darkened 9:16 backdrop (cheap to render vs. CSS blur)
    await sharp(out)
      .resize(270, 480, { fit: "cover" })
      .blur(14)
      .modulate({ brightness: 0.55, saturation: 0.9 })
      .jpeg({ quality: 85 })
      .toFile(path.join(bgDir, `0${sheetIdx}_${p + 1}.jpg`));
    sizes[`0${sheetIdx}_${p + 1}`] = [cx1 - cx0, ry1 - ry0];
    console.log(`${path.basename(out)}  ${cx1 - cx0}x${ry1 - ry0}`);
  }
};

const sizes = {};
(async () => {
  for (let i = 1; i <= 8; i++) await sliceSheet(i);
  fs.writeFileSync(
    path.join(root, "src", "data", "panelSizes.ts"),
    "// AUTO-GENERATED by scripts/sliceSheets.js\nexport const panelSizes: Record<string, [number, number]> = " +
      JSON.stringify(sizes, null, 1) +
      ";\n",
  );
})();
