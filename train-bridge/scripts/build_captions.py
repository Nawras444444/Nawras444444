"""Builds src/data/voiceData.ts from Whisper word timings (scripts/data/vo_words.json).
VO is split into clips that are re-placed onto the scene timeline."""
import json, os
FPS = 30
here = os.path.dirname(__file__)
words = json.load(open(os.path.join(here, "data", "vo_words.json")))
# silence ends from ffmpeg silencedetect (-35dB, 0.35s) -> fixes word starts swallowed by pauses
silences = [(4.366,4.988),(6.990,7.958),(12.700,13.397),(16.616,17.613),(19.806,20.400),(22.709,23.793),
            (25.746,26.145),(28.427,29.186),(30.082,30.795),(33.536,34.488),(35.806,36.551),(38.842,39.577),(40.591,41.127)]
for w in words:
    for s, e in silences:
        if s - 0.05 <= w["start"] < e:
            w["start"] = e
fix = {"واد": "وادٍ", "قطبان": "قضبان", "يصرق": "يصرخ", "ثوان": "ثوانٍ", "يفتح": "يُفتح"}
for w in words:
    w["text"] = fix.get(w["text"], w["text"])

AMBER, RED = "amber", "crimson"
hl = {"متران": AMBER, "فقط": AMBER, "السقوط": RED, "الهاوية": RED, "تجاهل": RED, "تحذير": AMBER,
      "العاصفة": AMBER, "انكشف": AMBER, "الجسر": AMBER, "المنهار": AMBER, "فجأة": RED,
      "زلقة": RED, "الانزلاق": RED, "للأسفل": RED, "الدفع": AMBER, "العكسي": AMBER, "ضغط": AMBER,
      "الهواء": AMBER, "حاسمة": RED, "يصرخ": RED, "المعدن": RED, "بشعرة": AMBER, "الصعداء": AMBER,
      "هادئ": AMBER, "نجوت": AMBER, "انظر": AMBER, "الأسفل": RED}

# (srcStart, srcEnd, frame at which srcStart plays, page word counts)
clips = [
    (0.00, 7.05, 3,    [5, 5, 5]),
    (7.85, 12.80, 433, [3, 4, 3]),
    (13.30, 16.70, 732, [5, 3]),
    (17.50, 22.80, 857, [4, 3, 5]),
    (23.70, 28.50, 1057, [5, 6]),
    (29.10, 33.60, 1263, [2, 5]),
    (34.40, 35.90, 1415, [3]),
    (36.45, 43.60, 1493, [3, 3, 3, 4, 3]),
]
out_clips, pages = [], []
wi = 0
for (s, e, at, counts) in clips:
    out_clips.append({"srcStartSec": s, "srcEndSec": e, "fromFrame": at})
    for c in counts:
        ws = []
        for w in words[wi:wi + c]:
            ws.append({"text": w["text"],
                       "startFrame": round(at + (w["start"] - s) * FPS),
                       "endFrame": round(at + (w["end"] - s) * FPS),
                       "highlight": hl.get(w["text"].strip("،."), None)})
        wi += c
        pages.append({"words": ws})
assert wi == len(words), (wi, len(words))

# Scene 2 has no narration in the recording -> on-screen text beat only
def text_beat(txt, start, per):
    ws = []
    for i, t in enumerate(txt.split(" ")):
        ws.append({"text": t, "startFrame": start + i * per, "endFrame": start + (i + 1) * per,
                   "highlight": {"منهار": RED, "بالكامل": RED, "عاصفة": AMBER, "للعودة.": AMBER}.get(t)})
    return {"words": ws, "textOnly": True}
s2 = [text_beat("جسر منهار بالكامل", 226, 9), text_beat("وسط عاصفة لا ترحم،", 290, 8), text_beat("ولا طريق للعودة.", 352, 10)]
pages = pages[:3] + s2 + pages[3:]

# page shows 3 frames before its first word, holds 18 frames after its last
# word, and never overlaps the next page
for p in pages:
    p["fromFrame"] = p["words"][0]["startFrame"] - 3
for i, p in enumerate(pages):
    last = p["words"][-1]["endFrame"] + 18
    nxt = pages[i + 1]["fromFrame"] if i + 1 < len(pages) else 10 ** 6
    p["toFrame"] = min(last, nxt)

ts = ["// AUTO-GENERATED by scripts/build_captions.py - do not edit by hand",
      "export type Highlight = 'amber' | 'crimson' | null;",
      "export type CaptionWord = {text: string; startFrame: number; endFrame: number; highlight: Highlight};",
      "export type CaptionPage = {fromFrame: number; toFrame: number; words: CaptionWord[]; textOnly?: boolean};",
      "export type VoClip = {srcStartSec: number; srcEndSec: number; fromFrame: number};",
      "export const voClips: VoClip[] = " + json.dumps(out_clips, ensure_ascii=False, indent=1) + ";",
      "export const captionPages: CaptionPage[] = " + json.dumps(pages, ensure_ascii=False, indent=1) + ";"]
open(os.path.join(here, "..", "src", "data", "voiceData.ts"), "w").write("\n".join(ts) + "\n")
for p in pages:
    print(p["fromFrame"], p["toFrame"], " ".join(w["text"] for w in p["words"]))
